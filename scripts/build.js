const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.join(__dirname, '..');
const output = path.join(root, 'dist');
const hash = value => createHash('sha256').update(value).digest('hex').slice(0, 12);
fs.mkdirSync(output, { recursive: true });
fs.cpSync(path.join(root, 'public'), output, { recursive: true });
const content = fs.readFileSync(path.join(root, 'data', 'portfolio.json'), 'utf8');
const contentName = `content.${hash(content)}.json`;
fs.writeFileSync(path.join(output, contentName), content);
const css = fs.readFileSync(path.join(root, 'public', 'styles.css'), 'utf8');
const cssName = `styles.${hash(css)}.css`;
fs.writeFileSync(path.join(output, cssName), css);
const app = fs.readFileSync(path.join(root, 'public', 'app.js'), 'utf8').replace('fetch("/api/content")', `fetch("./${contentName}")`);
const appName = `app.${hash(app)}.js`;
fs.writeFileSync(path.join(output, appName), app);
const html = fs.readFileSync(path.join(root, 'public', 'index.html'), 'utf8').replace('href="/styles.css"', `href="./${cssName}"`).replace('src="/app.js"', `src="./${appName}"`);
fs.writeFileSync(path.join(output, 'index.html'), html);
fs.writeFileSync(path.join(output, '.nojekyll'), '');
console.log('Built site with content-versioned CSS, JavaScript, and JSON.');
